from pathlib import Path
from subprocess import PIPE, Popen
from sys import argv, exit


def defineAST(
    outputDir: str,
    types: dict[str, list[str]],
    includes: list[str] = [],
) -> None:
    basePath = Path(outputDir)
    basePath.mkdir(parents=True, exist_ok=True)
    headerPath = basePath / "ast.hpp"

    bases = list(types.keys())

    with open(headerPath, "w", encoding="utf-8") as f:
        f.write("""// This file is generated by genAST.py. Do not edit manually.
#pragma once
#include <memory>
#include <variant>
#include <vector>
#include "token.hpp"

""")
        f.write("".join(f'#include "{inc}"\n' for inc in includes))
        f.write(
            """
namespace lox::ast {

"""
        )

        for base in bases:
            f.write(f"struct {base};\n")
            f.write(f"using {base}Ptr = std::unique_ptr<{base}>;\n")

        f.write("\n")

        for base, nodeTypes in types.items():
            nodes: list[tuple[str, list[tuple[str, str]]]] = []

            for t in nodeTypes:
                className, fields = t.split(" : ")
                className = className.strip()
                props: list[tuple[str, str]] = []

                for prop in fields.strip().split(","):
                    if not prop:
                        break
                    typ, name = prop.strip().split()
                    props.append((typ, name))

                nodes.append((className, props))

            for className, props in nodes:
                f.write(f"struct {className} {{\n")
                for typ, name in props:
                    fieldType = f"{typ}Ptr" if typ in bases else typ
                    f.write(f"\t{fieldType} {name};\n")
                f.write("};\n\n")

            variantList = ", ".join(className for className, _ in nodes)
            f.write(f"""using {base}Variant = std::variant<{variantList}>;
struct {base} : {base}Variant {{
    using {base}Variant::{base}Variant;
}};

// Wraps any alternative in a heap-allocated {base}, for building the
// {base.lower()} literal (or another {base}Ptr child) into a Binary/Unary/etc field.
inline {base}Ptr box({base} e) {{
    return std::make_unique<{base}>(std::move(e));
}}

""")

        f.write("} // namespace lox::ast\n")

    # Run clang-format on the file
    proc = Popen(["clang-format", "-i", str(headerPath)], stdout=PIPE, stderr=PIPE)
    _, stderr = proc.communicate()
    if proc.returncode != 0:
        print(f"Error running clang-format: {stderr.decode()}")
        exit(1)


if __name__ == "__main__":
    if len(argv) != 2:
        print("Usage: genAST <output directory>")
        exit(64)

    try:
        dir = argv[1]

        defineAST(
            dir,
            {
                "Expr": [
                    "Assign : lox::lexer::Token name, Expr val",
                    "Binary : Expr left, lox::lexer::Token op, Expr right",
                    "Unary : lox::lexer::Token op, Expr right",
                    "Ternary : Expr left, lox::lexer::Token op1, Expr mid, lox::lexer::Token op2, Expr right",
                    "Grouping : Expr expr",
                    "Literal : lox::lexer::Literal val",
                    "Variable : lox::lexer::Token name",
                    "Logical : Expr left, lox::lexer::Token op, Expr right",
                    "Call : Expr callee, lox::lexer::Token paren, std::vector<ExprPtr> args",
                    "Lambda : std::vector<lox::lexer::Token> params, std::vector<StmtPtr> body",
                ],
                "Stmt": [
                    "Block : std::vector<StmtPtr> stmts",
                    "Expression : ExprPtr expr",
                    "Function : lox::lexer::Token name, std::vector<lox::lexer::Token> params, std::vector<StmtPtr> body",
                    "If : ExprPtr condition, Stmt thenBr, Stmt elseBr",
                    "While : ExprPtr condition, Stmt body",
                    "For : Stmt init, ExprPtr condition, ExprPtr inc",
                    "Print : ExprPtr expr",
                    "Var : lox::lexer::Token name, ExprPtr init",
                    "Break : lox::lexer::Token keyword",
                    "Return : lox::lexer::Token keyword, ExprPtr val",
                ],
            },
        )
    except Exception as e:
        print(f"Error: {e}")
        exit(1)
