from pathlib import Path
from subprocess import PIPE, Popen
from sys import argv, exit


def defineAST(outputDir: str, base: str, types: list[str]) -> None:
    basePath = Path(outputDir)
    basePath.mkdir(parents=True, exist_ok=True)
    headerPath = basePath / f"{base.lower()}.hpp"

    nodes: list[tuple[str, list[tuple[str, str]]]] = []
    for t in types:
        className, fields = t.split(" : ")
        className = className.strip()
        props: list[tuple[str, str]] = []
        for prop in fields.strip().split(","):
            typ, name = prop.strip().split()
            props.append((typ, name))
        nodes.append((className, props))

    with open(headerPath, "w", encoding="utf-8") as f:
        f.write(f"""// This file is generated by genAST.py. Do not edit manually.
#pragma once
#include <memory>
#include <variant>
#include "token.hpp"

namespace lox::ast {{

struct {base};
using {base}Ptr = std::unique_ptr<{base}>;

""")
        for className, props in nodes:
            f.write(f"struct {className} {{\n")
            for typ, name in props:
                fieldType = f"{base}Ptr" if typ == base else typ
                f.write(f"\t{fieldType} {name};\n")
            f.write("};\n\n")

        variantList = ", ".join(className for className, _ in nodes)
        f.write(f"""using {base}Variant = std::variant<{variantList}>;
struct {base} : {base}Variant {{
    using {base}Variant::{base}Variant;
}};

// Wraps any alternative in a heap-allocated {base}, for building the
// {base.lower()} literal (or another {base}Ptr child) into a Binary/Unary/etc field.
inline {base}Ptr box({base} e) {{
    return std::make_unique<{base}>(std::move(e));
}}

}} // namespace lox::ast
""")
    # Run clang-format on the file
    proc = Popen(["clang-format", "-i", str(headerPath)], stdout=PIPE, stderr=PIPE)
    _, stderr = proc.communicate()
    if proc.returncode != 0:
        print(f"Error running clang-format: {stderr.decode()}")
        exit(1)


if __name__ == "__main__":
    if len(argv) != 2:
        print("Usage: genAST <output directory>")
        exit(64)
    try:
        defineAST(
            argv[1],
            "Expr",
            [
                "Binary : Expr left, lox::lexer::Token op, Expr right",
                "Unary : lox::lexer::Token op, Expr right",
                "Ternary : Expr left, lox::lexer::Token op1, Expr mid, lox::lexer::Token op2, Expr right",
                "Grouping : Expr expr",
                "Literal : lox::lexer::Literal val",
            ],
        )
    except Exception as e:
        print(f"Error: {e}")
        exit(1)
